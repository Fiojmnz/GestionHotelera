    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el código de la reserva.");
            return;
        }

        reservaEncontrada = null;

        for (Modelo.Reserva r : Modelo.GestorHotel.getInstancia().getReservas()) {

            if (r.getCodigo().equalsIgnoreCase(codigo)) {
                reservaEncontrada = r;
                break;
            }
        }

        if (reservaEncontrada == null) {

            JOptionPane.showMessageDialog(this,
                    "No se encontró ninguna reserva con ese código");

            lblDatoHuesped.setText("Sin información");
            lblDatoHabitacion.setText("Sin información");
            lblDatoEntrada.setText("Sin información");
            lblDatoSalida.setText("Sin información");
            lblDatoEstado.setText("Sin información");

            return;
        }

// Mostrar información de la reserva
        lblDatoHuesped.setText(reservaEncontrada.getHuesped().getNombre());

        lblDatoHabitacion.setText(
                String.valueOf(reservaEncontrada.getHabitacion().getNumero()));

        lblDatoEntrada.setText(
                reservaEncontrada.getFechaEntrada().toString());

        lblDatoSalida.setText(
                reservaEncontrada.getFechaSalida().toString());

        lblDatoEstado.setText(reservaEncontrada.getEstado());

        JOptionPane.showMessageDialog(this,
                "Reserva encontrada correctamente");
    }//GEN-LAST:event_btnBuscarActionPerformed

