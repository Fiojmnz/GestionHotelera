    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        btnIniciar.setEnabled(false);

        txtRevisadas.setText("0");
        txtVencidas.setText("0");
        txtConfirmadas.setText("0");
        txtActividad.setText("");

        lblEstado.setText("Simulación en proceso...");

        Hilos.SimuladorVencimientos simulador
                = new Hilos.SimuladorVencimientos(
                        mensaje -> javax.swing.SwingUtilities.invokeLater(() -> {

                            txtActividad.append(mensaje + "\n");

                            if (mensaje.startsWith("Simulación finalizada")
                                    || mensaje.startsWith("Simulación interrumpida")) {

                                lblEstado.setText("Simulación finalizada");
                                btnIniciar.setEnabled(true);
                            }
                        }),
                        datos -> javax.swing.SwingUtilities.invokeLater(() -> {

                            txtRevisadas.setText(String.valueOf(datos[0]));
                            txtVencidas.setText(String.valueOf(datos[1]));
                            txtConfirmadas.setText(String.valueOf(datos[2]));

                        })
                );

        Thread hilo = new Thread(simulador);
        hilo.start();
    }//GEN-LAST:event_btnIniciarActionPerformed

