    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        try {
    LocalDate fecha = LocalDate.parse(
            txtFechaConsulta.getText().trim());
    if (fecha.isBefore(LocalDate.now())) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "La fecha no puede ser anterior a hoy");
    return;
}
txtHabitacionesDisponibles.setText("");
lblCantidad.setText("Habitaciones disponibles: 0");

    List<Habitacion> disponibles =
            controlador.consultarDisponibilidad(fecha);
    

    int cantidad = controlador.contarDisponibles(fecha);

    lblCantidad.setText(
            "Habitaciones disponibles: " + cantidad);

    StringBuilder texto = new StringBuilder();

    for (Habitacion h : disponibles) {
        texto.append(h.getNumero()).append(", ");
    }

    if (disponibles.isEmpty()) {
        txtHabitacionesDisponibles.setText(
                "No hay habitaciones disponibles.");
    } else {
        texto.setLength(texto.length() - 2);
        txtHabitacionesDisponibles.setText(
                texto.toString());
    }

} catch (java.time.format.DateTimeParseException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Ingrese una fecha válida con formato AAAA-MM-DD");
    
    
}
        
        
    }//GEN-LAST:event_btnConsultarActionPerformed

